"""Generate tests/data/reads_random_pmdtools_ds3.tsv: the DS:Z values PMDtools 0.60 writes with
`--threshold 3 --writesamfield` on tests/data/reads_random.sam (kept reads, in output order).

Clean room: PMDtools is only run, never read.

Usage (PMDtools 0.60 path inside WSL; see gen_site_terms.py):
    py -3 -I tests/oracle/gen_writesamfield.py <pmdtools.0.60.py in WSL> tests/data
"""
import subprocess
import sys


def main():
    pmdtools, outdir = sys.argv[1], sys.argv[2]
    with open(f"{outdir}/reads_random.sam", encoding="utf-8") as f:
        sam = f.read()
    out = subprocess.run(["wsl", "-e", "python3", "-W", "ignore", pmdtools,
                          "--threshold", "3", "--writesamfield"],
                         input=sam.encode(), capture_output=True, check=True).stdout.decode()
    with open(f"{outdir}/reads_random_pmdtools_ds3.tsv", "w", newline="\n") as f:
        f.write("# DS:Z values written by PMDtools 0.60 --threshold 3 --writesamfield on reads_random.sam.\n")
        f.write("# Generated by tests/oracle/gen_writesamfield.py; do not edit by hand.\n")
        f.write("read_name\tDS\n")
        for line in out.splitlines():
            if not line or line.startswith("@"):
                continue
            fields = line.split("\t")
            ds = [x for x in fields[11:] if x.startswith("DS:Z:")]
            f.write(f"{fields[0]}\t{ds[0][5:]}\n")


if __name__ == "__main__":
    main()
