"""Generate tests/data/pmdtools_site_terms.tsv by running PMDtools 0.60.

Clean room: PMDtools is only run, never read. Each synthetic read has exactly one
informative site (a reference C; every other base is A), so the PMD score PMDtools
prints for that read is the contribution of that one site.

Requirements:
- PMDtools 0.60 from the Bioconda source archive
  (https://github.com/pontussk/PMDtools/archive/0.60.tar.gz, md5 c059d7ab4c24e1ce00f1eee4c2a4b669).
- It needs /dev/null, so on Windows it is run under WSL.

Usage:
    py -3 -I tests/oracle/gen_site_terms.py <path-to-pmdtools.0.60.py inside WSL> > tests/data/pmdtools_site_terms.tsv
"""
import subprocess
import sys

PARAM_SETS = [
    # (p, c, pi_ancient, pi_contamination)
    (0.3, 0.01, 0.001, 0.001),  # PMDtools defaults
    (0.5, 0.01, 0.001, 0.001),
    (0.3, 0.0, 0.001, 0.001),
    (0.3, 0.01, 0.005, 0.001),
    (0.3, 0.01, 0.001, 0.005),
    (0.1, 0.02, 0.002, 0.003),
]
DS_QUALS = [0, 2, 10, 20, 30, 37, 40, 60, 93]
SS_QUALS = [2, 20, 40]
DS_LENGTH = 40
SS_LENGTHS = [30, 61]


def sam_line(i, read_len, pos, read_base, q):
    """One read of length read_len with a reference C at 1-based position pos."""
    ref = ["A"] * read_len
    ref[pos - 1] = "C"
    seq = list(ref)
    seq[pos - 1] = read_base
    if read_base == "C":
        md = str(read_len)
    else:
        md = f"{pos - 1}C{read_len - pos}"
    qual = chr(33 + q) * read_len
    return "\t".join([f"r{i}", "0", "chrT", "100", "37", f"{read_len}M", "*", "0", "0",
                      "".join(seq), qual, f"MD:Z:{md}"])


def run_pmdtools(pmdtools, lines, args):
    header = "@HD\tVN:1.6\n@SQ\tSN:chrT\tLN:100000\n"
    text = header + "\n".join(lines) + "\n"
    out = subprocess.run(["wsl", "-e", "python3", "-W", "ignore", pmdtools, "--printDS"] + args,
                         input=text.encode(), capture_output=True, check=True).stdout.decode()
    scores = [line.split("\t")[-1].strip() for line in out.splitlines() if line.strip()]
    if len(scores) != len(lines):
        sys.exit(f"expected {len(lines)} scores, got {len(scores)}")
    return scores


def param_args(p, c, pi_a, pi_c):
    return ["--PMDpparam", str(p), "--PMDconstant", str(c),
            "--polymorphism_ancient", str(pi_a), "--polymorphism_contamination", str(pi_c)]


def main():
    pmdtools = sys.argv[1]
    print("# Per-site PMD score terms printed by PMDtools 0.60 (--printDS, last column).")
    print("# One informative site per read: reference C, read C (match) or T (mismatch).")
    print("# ds: z = 1-based position from the 5' end. ss (--ss): z from 5', y from 3'.")
    print("# Generated by tests/oracle/gen_site_terms.py; do not edit by hand.")
    print("mode\tz\ty\tq\tis_match\tp\tc\tpi_ancient\tpi_contamination\tpmds")
    for params in PARAM_SETS:
        rows, lines = [], []
        for q in DS_QUALS:
            for z in range(1, DS_LENGTH + 1):
                for is_match in (1, 0):
                    lines.append(sam_line(len(lines), DS_LENGTH, z, "C" if is_match else "T", q))
                    rows.append(("ds", z, 0, q, is_match))
        for row, score in zip(rows, run_pmdtools(pmdtools, lines, param_args(*params))):
            print("\t".join(str(x) for x in row + params) + "\t" + score)
    for params in PARAM_SETS[:2]:
        rows, lines = [], []
        for read_len in SS_LENGTHS:
            for q in SS_QUALS:
                for z in range(1, read_len + 1):
                    for is_match in (1, 0):
                        lines.append(sam_line(len(lines), read_len, z, "C" if is_match else "T", q))
                        rows.append(("ss", z, read_len - z + 1, q, is_match))
        for row, score in zip(rows, run_pmdtools(pmdtools, lines, ["--ss"] + param_args(*params))):
            print("\t".join(str(x) for x in row + params) + "\t" + score)


if __name__ == "__main__":
    main()
