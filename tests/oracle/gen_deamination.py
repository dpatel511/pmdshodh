"""Generate tests/data/reads_random_pmdtools_deamination.tsv: PMDtools 0.60 `--deamination --range 30`
tables for tests/data/reads_random.sam in three treatment modes. Clean room: PMDtools is only run.

Usage (PMDtools 0.60 path inside WSL; see gen_site_terms.py):
    py -3 -I tests/oracle/gen_deamination.py <pmdtools.0.60.py in WSL> tests/data
"""
import subprocess
import sys

MODES = {"none": [], "full": ["--CpG"], "half": ["--UDGhalf"]}


def main():
    pmdtools, outdir = sys.argv[1], sys.argv[2]
    with open(f"{outdir}/reads_random.sam", encoding="utf-8") as f:
        sam = f.read().encode()
    with open(f"{outdir}/reads_random_pmdtools_deamination.tsv", "w", newline="\n") as out:
        out.write("# PMDtools 0.60 --deamination --range 30 on reads_random.sam (fractions, 5 decimals).\n")
        out.write("# z = 0 is the terminal base; C columns from the 5' end, G columns from the 3' end.\n")
        out.write("# Generated by tests/oracle/gen_deamination.py; do not edit by hand.\n")
        out.write("treatment\tz\tCT\tCA\tCG\tCC\tGA\tGT\tGC\tGG\n")
        for mode, opts in MODES.items():
            res = subprocess.run(["wsl", "-e", "python3", "-W", "ignore", pmdtools, "--deamination",
                                  "--range", "30"] + opts, input=sam, capture_output=True, check=True)
            for line in res.stdout.decode().splitlines():
                if line[:1].isdigit():
                    out.write(mode + "\t" + "\t".join(line.split()) + "\n")


if __name__ == "__main__":
    main()
